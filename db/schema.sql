-- Dongbaek OnePass MVP PostgreSQL schema (ERD 2026-10-24)
-- 23 tables: 20 logical + 3 registration/demo tables. All data is synthetic unless verified.
-- Non-destructive initial creation only. IF NOT EXISTS does not migrate existing tables.
-- Date intervals are [valid_from, valid_to); simulation events/results stay in CSV.
-- The three registration/demo tables are placed in the same DB for this MVP; no cross-namespace FKs.
-- Timestamp values are stored as local Asia/Seoul wall-clock time, as specified in the ERD.
BEGIN;

-- CARD_PRODUCT
CREATE TABLE IF NOT EXISTS card_product (
    product_id TEXT,
    product_name TEXT,
    issuer TEXT,
    card_type TEXT,
    product_status TEXT,
    terms_version TEXT,
    source_status TEXT,
    source_ref TEXT,
    CONSTRAINT pk_card_product PRIMARY KEY (product_id),
    CONSTRAINT ck_card_product_issuer CHECK (issuer IN ('BNK_BUSAN', 'DONGBAEKJEON')),
    CONSTRAINT ck_card_product_card_type CHECK (card_type IN ('DONGBAEK_CHECK', 'DONGBAEK_PREPAID', 'BANK_CHECK', 'BANK_CREDIT')),
    CONSTRAINT ck_card_product_product_status CHECK (product_status IN ('ACTIVE', 'ENDED', 'TEST_ONLY')),
    CONSTRAINT ck_card_product_source_status CHECK (source_status IN ('VERIFIED', 'SYNTHETIC', 'ASSUMED', 'PENDING'))
);

